package spannerdiff

import "testing"

func TestDiffView(t *testing.T) {
	runDiffTests(t, DiffOption{ErrorOnUnsupportedDDL: true}, map[string]diffTest{
		"create view": {
			``,
			`
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1;`,
			`
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1;`,
			false,
		},
		"create view referencing recreated table": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_I2 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);`,
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_I2 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1, T1_I2);
			CREATE VIEW V1 SQL SECURITY INVOKER AS SELECT T1_I1 FROM T1;`,
			`
			DROP TABLE T1;
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_I2 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1, T1_I2);
			CREATE VIEW V1 SQL SECURITY INVOKER AS SELECT T1_I1 FROM T1;`,
			false,
		},
		"drop view": {
			`
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1;`,
			``,
			`
			DROP VIEW V1;`,
			false,
		},
		"recreate view": {
			`
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1;`,
			`
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1 WHERE T1_I1 > 0;`,
			`
			CREATE OR REPLACE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1 WHERE T1_I1 > 0;`,
			false,
		},
		"replace view to change MATCH to OPTIONAL MATCH": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE PROPERTY GRAPH G1 NODE TABLES (T1);
			CREATE VIEW V1 SQL SECURITY INVOKER AS SELECT * FROM GRAPH_TABLE(G1 MATCH (n) RETURN n.T1_I1);`,
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE PROPERTY GRAPH G1 NODE TABLES (T1);
			CREATE VIEW V1 SQL SECURITY INVOKER AS SELECT * FROM GRAPH_TABLE(G1 OPTIONAL MATCH (n) RETURN n.T1_I1);`,
			`
			CREATE OR REPLACE VIEW V1 SQL SECURITY INVOKER AS SELECT * FROM GRAPH_TABLE(G1 OPTIONAL MATCH (n) RETURN n.T1_I1);`,
			false,
		},
		"drop and create view": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1;`,
			`
			CREATE TABLE T1 (
			  T1_S1 STRING(MAX) NOT NULL,
			) PRIMARY KEY(T1_S1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1;`,
			`
			DROP VIEW V1;
			DROP TABLE T1;
			CREATE TABLE T1 (
			  T1_S1 STRING(MAX) NOT NULL,
			) PRIMARY KEY(T1_S1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT * FROM T1;`,
			false,
		},
		"recreate view referencing dropped table": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE TABLE T2 (
			  T2_I1 INT64 NOT NULL,
			) PRIMARY KEY(T2_I1);
			CREATE VIEW V1 SQL SECURITY INVOKER AS SELECT T1.T1_I1 FROM T1;`,
			`
			CREATE TABLE T2 (
			  T2_I1 INT64 NOT NULL,
			) PRIMARY KEY(T2_I1);
			CREATE VIEW V1 SQL SECURITY INVOKER AS SELECT T2.T2_I1 FROM T2;`,
			`
			DROP VIEW V1;
			DROP TABLE T1;
			CREATE VIEW V1 SQL SECURITY INVOKER AS SELECT T2.T2_I1 FROM T2;`,
			false,
		},
		"add column referenced by new view with grant": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE ROLE R1;`,
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_I2 INT64,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_I1, T1.T1_I2 FROM T1;
			CREATE ROLE R1;
			GRANT SELECT ON VIEW V1 TO ROLE R1;`,
			`
			ALTER TABLE T1 ADD COLUMN T1_I2 INT64;
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_I1, T1.T1_I2 FROM T1;
			GRANT SELECT ON VIEW V1 TO ROLE R1;`,
			false,
		},
		"drop column referenced by view": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_I2 INT64,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1_I1, T1_I2 FROM T1;`,
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1_I1 FROM T1;`,
			`
			DROP VIEW V1;
			ALTER TABLE T1 DROP COLUMN T1_I2;
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1_I1 FROM T1;`,
			false,
		},
		"drop column referenced by view with grant": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_I2 INT64,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_I1, T1.T1_I2 FROM T1;
			CREATE ROLE R1;
			GRANT SELECT ON VIEW V1 TO ROLE R1;`,
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_I1 FROM T1;
			CREATE ROLE R1;
			GRANT SELECT ON VIEW V1 TO ROLE R1;`,
			`
			REVOKE SELECT ON VIEW V1 FROM ROLE R1;
			DROP VIEW V1;
			ALTER TABLE T1 DROP COLUMN T1_I2;
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_I1 FROM T1;
			GRANT SELECT ON VIEW V1 TO ROLE R1;`,
			false,
		},
		"change type of column referenced by view": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_S1 STRING(MAX),
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_S1 FROM T1;`,
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_S1 INT64,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_S1 FROM T1;`,
			`
			DROP VIEW V1;
			ALTER TABLE T1 DROP COLUMN T1_S1;
			ALTER TABLE T1 ADD COLUMN T1_S1 INT64;
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1.T1_S1 FROM T1;`,
			false,
		},
		"drop column not referenced by view": {
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			  T1_I2 INT64,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1_I1 FROM T1;`,
			`
			CREATE TABLE T1 (
			  T1_I1 INT64 NOT NULL,
			) PRIMARY KEY(T1_I1);
			CREATE VIEW V1 SQL SECURITY DEFINER AS SELECT T1_I1 FROM T1;`,
			`
			ALTER TABLE T1 DROP COLUMN T1_I2;`,
			false,
		},
	})
}
